#!/usr/bin/env python3
"""Fail-closed, offline stress evidence review (no Jetson or network access).

Usage: python3 stress-evaluate.py logs-stress [veryfast|faster]
The MP4 JSON is generated by the runner by decoding the entire transferred file.
"""
import json
import math
import re
import statistics
import sys
from datetime import datetime, timedelta
from pathlib import Path


def percentile(values, p):
    ordered = sorted(values)
    return ordered[math.ceil(p * len(ordered)) - 1]


def fields(line):
    return dict(re.findall(r'([a-z_][a-z_0-9]*)=([^\s]+)', line))


def number(data, key):
    try:
        value = float(data[key])
        return value if math.isfinite(value) else float('-inf')
    except (KeyError, TypeError, ValueError):
        return float('-inf')


def cpu_stats(path):
    previous, samples, times = {}, {}, {}
    stamp = None
    for line in path.read_text().splitlines():
        if line.startswith('cpu'):
            parts = line.split()
            if not re.fullmatch(r'cpu\d+', parts[0]) or len(parts) < 9:
                continue
            ticks = [int(tick) for tick in parts[1:]]
            busy = sum(ticks[:3]) + sum(ticks[5:8])
            # guest/guest_nice duplicate user/nice and are not extra elapsed ticks.
            total = sum(ticks[:8])
            if parts[0] in previous:
                old_busy, old_total = previous[parts[0]]
                if total > old_total:
                    samples.setdefault(parts[0], []).append(100 * (busy - old_busy) / (total - old_total))
                    if stamp is not None:
                        times.setdefault(parts[0], []).append(stamp)
            previous[parts[0]] = busy, total
        else:
            stamp = parse_time(line.strip())
    return ({core: {'mean_pct': round(statistics.mean(vals), 2), 'p95_pct': round(percentile(vals, .95), 2),
                    'samples': len(vals)} for core, vals in samples.items() if vals}, times)


def parse_time(value, tegra=False):
    try:
        return (datetime.strptime(value[:19], '%m-%d-%Y %H:%M:%S') if tegra else
                datetime.fromisoformat(value.split()[0]).replace(tzinfo=None))
    except ValueError:
        return None


def covered(times, start, minutes):
    counts = [0] * minutes
    for stamp in times:
        minute = int((stamp - start).total_seconds() // 60)
        if 0 <= minute < minutes:
            counts[minute] += 1
    return all(count >= 54 for count in counts)


def summarize(root, preset='veryfast', minutes=90):
    if preset not in ('veryfast', 'faster') or minutes < 1:
        raise ValueError('preset must be veryfast/faster and minutes must be positive')
    source = root / preset
    seconds = minutes * 60
    lines = (source / 'e2e.log').read_text().splitlines()
    all_windows = [fields(line) for line in lines if line.startswith('minute=')]
    windows = [w for w in all_windows if number(w, 'minute') <= minutes]
    # Minute N covers the steady-state interval [5+60*(N-1), 5+60*N] seconds.
    if any(w.get('elapsed_s') is None for w in windows):
        raise ValueError('missing minute window duration')
    final = [fields(line) for line in lines if line.startswith('final ')]
    bad_minutes = []
    seen = set()
    for window in windows:
        minute = number(window, 'minute')
        capture = window.get('capture_fps', '').split(',')
        good = (minute.is_integer() and 1 <= minute <= minutes and minute not in seen and
                minute * 60 + 4 <= number(window, 'elapsed_s') <= minute * 60 + 10 and len(capture) == 2 and
                all(number({'fps': fps}, 'fps') >= 29.5 for fps in capture) and
                number(window, 'paired_pct') >= 99 and number(window, 'render_fps') >= 29.5 and
                0 <= number(window, 'render_ms_mean') <= 33.34 and
                number(window, 'infer_hz') >= 14.9 and number(window, 'infer_batches') >= 899 and
                number(window, 'analysis_skipped') == 0 and
                0 <= number(window, 'infer_p99_ms') <= 66.7 and
                number(window, 'mp4_fps') >= 29.5 and number(window, 'rtmp_fps') >= 29.5 and
                window.get('no_drop') == 'PASS')
        if not good:
            bad_minutes.append(minute if math.isfinite(minute) else window.get('minute', '?'))
        seen.add(minute)
    missing_minutes = sorted(set(range(1, minutes + 1)) - seen)
    monitor = [(parse_time(line), int(match[1]))
               for line in (source / 'monitor.log').read_text().splitlines()
               if (match := re.search(r'MemAvailable_kib=(\d+)', line))]
    memory = [value for _, value in monitor]
    cores, cpu_times = cpu_stats(source / 'cores.log')
    tegra_path = source / 'tegrastats.log'
    tegra_lines = tegra_path.read_text().splitlines() if tegra_path.exists() else []
    gpu_samples = [(parse_time(line, tegra=True), int(match[1])) for line in tegra_lines
                   if (match := re.search(r'\bGR3D_FREQ (\d+)%', line))]
    tj_samples = [(parse_time(line, tegra=True), float(match[1])) for line in tegra_lines
                  if (match := re.search(r'\btj@([\d.]+)C', line))]
    gpu = [value for _, value in gpu_samples]
    tj = [value for _, value in tj_samples]
    gpu_stats = {'mean_pct': round(statistics.mean(gpu), 2), 'p95_pct': percentile(gpu, .95)} if gpu else {}
    slice_seconds = min(900, seconds // 2)
    stamps = [stamp for stamp in ([time for time, _ in monitor] +
              [time for times in cpu_times.values() for time in times] +
              [time for time, _ in gpu_samples] + [time for time, _ in tj_samples]) if stamp is not None]
    start = min(stamps) if stamps else None
    def times_covered(times):
        times = [stamp for stamp in times if stamp is not None]
        return (start is not None and times and (max(times) - min(times)).total_seconds() >= seconds - 3 and
                covered(times, start, minutes))
    trips_path = source / 'thermal-trips.log'
    trips = []
    sensor = ''
    for line in trips_path.read_text().splitlines() if trips_path.exists() else []:
        if line.startswith('zone='):
            sensor = fields(line).get('type', '').lower()
        match = re.search(r'trip_point_\d+_type=(\S+) temperature_millic=(\d+)', line)
        if match and ('gpu' in sensor or 'tj' in sensor or 'junction' in sensor) and match[1] in ('passive', 'hot', 'critical'):
            trips.append(int(match[2]) / 1000)
    trip_c = min(trips) if trips else None
    first_slice = [value for stamp, value in tj_samples if stamp is not None and start is not None and
                   start + timedelta(seconds=seconds - 2 * slice_seconds) <= stamp <
                   start + timedelta(seconds=seconds - slice_seconds)]
    last_slice = [value for stamp, value in tj_samples if stamp is not None and start is not None and
                  start + timedelta(seconds=seconds - slice_seconds) <= stamp <
                  start + timedelta(seconds=seconds)]
    thermal = {'max_c': max(tj), 'last_15m_delta_c': round(statistics.mean(last_slice) -
                statistics.mean(first_slice), 2),
                'trip_c': trip_c, 'trip_margin_c': round(trip_c - max(tj), 2) if trip_c is not None else None
                } if first_slice and last_slice else {'trip_c': trip_c}
    kernel_path = source / 'kernel.log'
    kernel = kernel_path.read_text() if kernel_path.exists() else ''
    viewer = json.loads((root / f'{preset}-viewer.log').read_text())
    mp4 = json.loads((root / f'{preset}-mp4.json').read_text())
    # The 90-minute thermal trend needs two complete 15-minute steady-state slices.
    telemetry_ok = (times_covered([stamp for stamp, _ in monitor]) and bool(cores) and
                    all(times_covered(cpu_times.get(core, [])) for core in cores) and
                    times_covered([stamp for stamp, _ in gpu_samples]) and
                    times_covered([stamp for stamp, _ in tj_samples]))
    limits = {
        'all_minutes': len(windows) == minutes and not missing_minutes and not bad_minutes,
        'final_acceptance': bool(final) and final[-1].get('acceptance') == 'PASS' and
            all(w.get('no_drop') == 'PASS' for w in all_windows[minutes:]),
        'telemetry_coverage': telemetry_ok and (source / 'power-mode.log').exists() and
            bool((source / 'power-mode.log').read_text().strip()),
        'cpu': bool(cores) and all(stat['mean_pct'] <= 80 and stat['p95_pct'] <= 95
                                   for stat in cores.values()),
        'gpu': bool(gpu) and gpu_stats['mean_pct'] <= 80 and gpu_stats['p95_pct'] <= 95,
        'memory': bool(memory) and min(memory) >= 1048576,
        'thermal': bool(tj) and trip_c is not None and 'max_c' in thermal and
            thermal['trip_margin_c'] >= 10 and thermal['last_15m_delta_c'] <= 3,
        'no_throttling': bool(kernel.strip()) and not re.search(
            r'(?i)(?:thermal[^\n]*throttl|throttl[^\n]*thermal|overheat|soctherm[^\n]*trip)', kernel),
        'mp4': number(mp4, 'width') == 1920 and number(mp4, 'height') == 1080 and
            number(mp4, 'duration') >= seconds - 1 and number(mp4, 'measured_fps') >= 29.5 and
            number(mp4, 'nb_read_frames') >= 29.5 * seconds,
        'viewer': viewer.get('full_window') is True and number(viewer, 'elapsed_s') >= seconds and
            number(viewer, 'decoded_fps') >= 29.5 and number(viewer, 'pts_fps') >= 29.5 and
            number(viewer, 'decoded_frames') >= 29.5 * seconds and
            number(viewer, 'missed_segments') == 0 and number(viewer, 'pts_discontinuities') == 0,
    }
    return {'preset': preset, 'status': 'PASS' if all(limits.values()) else 'FAIL',
            'headroom': limits['telemetry_coverage'] and all(
                limits[key] for key in ('cpu', 'gpu', 'memory', 'thermal', 'no_throttling')),
            'limits': limits, 'bad_minutes': bad_minutes, 'missing_minutes': missing_minutes,
            'cpu_per_core': cores, 'gpu': gpu_stats, 'memory_min_kib': min(memory) if memory else None,
            'thermal': thermal, 'telemetry_samples': {'memory': len(memory), 'gpu': len(gpu), 'tj': len(tj)},
            'mp4': mp4, 'viewer': viewer}


def main():
    root = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).parent / 'logs-stress'
    preset = sys.argv[2] if len(sys.argv) > 2 else 'veryfast'
    try:
        result = summarize(root, preset, minutes=90 if preset == 'veryfast' else 10)
    except (OSError, ValueError, KeyError, IndexError, ZeroDivisionError) as exc:
        result = {'preset': preset, 'status': 'NO_COMPLETE_EVIDENCE', 'error': str(exc)}
    print(json.dumps(result, sort_keys=True))
    return 0 if result['status'] == 'PASS' else 1


if __name__ == '__main__':
    sys.exit(main())
